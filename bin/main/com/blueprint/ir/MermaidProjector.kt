package com.blueprint.ir

import com.intellij.openapi.components.Service
import com.intellij.openapi.project.Project

/**
 * Renders an ArchitectureIR as a Mermaid classDiagram.
 *
 * Pure logic lives in [MermaidProjection] so tests and headless callers can
 * render without a Project.
 */
@Service(Service.Level.PROJECT)
class MermaidProjector(private val project: Project) {
    fun render(ir: ArchitectureIR, filesScanned: Int = 0): String =
        MermaidProjection.render(ir, fallbackProjectName = project.name, filesScanned = filesScanned)
}

object MermaidProjection {

    fun render(ir: ArchitectureIR, fallbackProjectName: String = "", filesScanned: Int = 0): String = buildString {
        appendLine("classDiagram")
        appendLine("%% Generated by Blueprint from project: ${ir.project.name.ifBlank { fallbackProjectName }}")
        if (filesScanned > 0) appendLine("%% Files scanned: $filesScanned")
        if (ir.project.sourceRoots.isNotEmpty()) {
            appendLine("%% Source roots: ${ir.project.sourceRoots.joinToString(", ")}")
        }
        appendLine("%% Components: ${ir.components.size}  Contracts: ${ir.contracts.size}  DataTypes: ${ir.dataTypes.size}")
        appendLine()

        if (ir.components.isEmpty()) {
            appendLine("%% No components recovered.")
            appendLine("%% Add or paste Mermaid class blocks here before importing, for example:")
            appendLine("%%")
            appendLine("%% class Invite {")
            appendLine("%%   id: str")
            appendLine("%%   email: str")
            appendLine("%% }")
            return@buildString
        }

        val components = ir.components.sortedWith(
            compareBy({ it.ownership.files.firstOrNull() ?: "" }, { it.name })
        )
        val contractsById = ir.contracts.associateBy { it.id }

        components.forEach { component ->
            val kindMarker = when (component.kind) {
                ComponentKind.PORT -> "&lt;&lt;interface&gt;&gt;"
                ComponentKind.MODEL -> "&lt;&lt;${component.tags.firstOrNull() ?: "model"}&gt;&gt;"
                ComponentKind.REGISTRY -> "&lt;&lt;registry&gt;&gt;"
                ComponentKind.CLI -> "&lt;&lt;cli&gt;&gt;"
                ComponentKind.JOB -> "&lt;&lt;job&gt;&gt;"
                ComponentKind.ADAPTER -> "&lt;&lt;adapter&gt;&gt;"
                ComponentKind.TEST -> "&lt;&lt;test&gt;&gt;"
                ComponentKind.SERVICE -> if (component.concurrency == Concurrency.ASYNC) "&lt;&lt;async service&gt;&gt;" else null
                else -> null
            }
            appendLine("class ${component.name} {")
            if (kindMarker != null) appendLine("  $kindMarker")
            component.fields.take(14).forEach { field ->
                val typeStr = field.type.toString().toMermaidType()
                appendLine("  ${field.name}: $typeStr")
            }
            component.operations.take(10).forEach { op ->
                val prefix = if (op.concurrency == Concurrency.ASYNC) "+async " else "+"
                appendLine("  $prefix${op.name}()")
            }
            appendLine("}")
            component.provides.forEach { cid ->
                contractsById[cid]?.let { appendLine("%% ${component.name} provides ${it.name}") }
            }
            appendLine()
        }

        val edges = ir.edges
            .filter { it.toKind == EdgeTargetKind.COMPONENT }
            .mapNotNull { edge ->
                val from = components.firstOrNull { it.id == edge.from }?.name ?: return@mapNotNull null
                val to = components.firstOrNull { it.id == edge.to }?.name ?: return@mapNotNull null
                val label = when (edge.kind) {
                    EdgeKind.EXTENDS -> "extends"
                    EdgeKind.CONTAINS -> "contains"
                    EdgeKind.REFERENCES -> "references"
                    EdgeKind.CALLS -> "calls"
                    EdgeKind.EMITS -> "emits"
                    EdgeKind.LISTENS -> "listens"
                    EdgeKind.REGISTERS_WITH -> "registers with"
                    EdgeKind.READS -> "reads"
                    EdgeKind.WRITES -> "writes"
                }
                "$from --> $to : $label"
            }
            .distinct()
            .sorted()

        edges.forEach { appendLine(it) }

        if (ir.coverage != null) {
            appendLine()
            appendLine("%% Recovery coverage: ${ir.coverage.componentsRecovered}/${ir.coverage.componentsTotal} components, ${ir.coverage.contractsRecovered} contracts")
            if (ir.coverage.opaqueZones.isNotEmpty()) {
                appendLine("%% Opaque annotations: ${ir.coverage.opaqueZones.size}")
            }
        }
    }.trim()

    private fun String.toMermaidType(): String =
        replace("{", "[")
            .replace("}", "]")
            .replace("<", "[")
            .replace(">", "]")
            .replace('\n', ' ')
            .trim()
            .ifBlank { "Any" }
}
